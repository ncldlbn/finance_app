-- Schema PostgreSQL di Finance Tracker (equivale allo schema SQLite all'ultima migrazione).
--
-- Le query dell'app sono scritte una volta sola e valgono per entrambi i database; per questo qui si
-- ricreano le tre cose di SQLite che usano:
--   * current_uid()  : l'utente a cui appartiene la connessione (impostato da db.py con set_config);
--                      senza utente solleva un errore, così nessuna query può mescolare dati di utenti diversi;
--   * strftime(f, d) : i formati usati dall'app (%Y, %m, %d, %Y-%m, %Y-%m-%d) su date testuali AAAA-MM-GG;
--   * COLLATE NOCASE : un ordinamento ICU che ignora maiuscole/minuscole (nome «nocase»).
-- Le date restano testo ISO (AAAA-MM-GG) come in SQLite: i confronti tra stringhe funzionano allo stesso modo.

CREATE COLLATION IF NOT EXISTS nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

CREATE OR REPLACE FUNCTION current_uid() RETURNS integer LANGUAGE plpgsql STABLE AS $$
DECLARE v text := current_setting('app.user_id', true);
BEGIN
    IF v IS NULL OR v = '' THEN
        RAISE EXCEPTION 'Nessun utente associato a questa connessione';
    END IF;
    RETURN v::integer;
END $$;

CREATE OR REPLACE FUNCTION strftime(fmt text, d text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT to_char(d::date, replace(replace(replace(fmt, '%Y', 'YYYY'), '%m', 'MM'), '%d', 'DD'))
$$;

CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text COLLATE nocase NOT NULL UNIQUE,
    password_hash text NOT NULL,
    is_demo       integer NOT NULL DEFAULT 0,
    data_date     text NOT NULL DEFAULT '',
    created_at    text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    theme         text NOT NULL DEFAULT 'auto'
);

CREATE TABLE category (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  integer NOT NULL DEFAULT 1,
    type     text NOT NULL CHECK (type IN ('essential', 'extra')),
    category text NOT NULL,
    budget   double precision DEFAULT 0,
    visible  integer NOT NULL DEFAULT 1,
    position integer NOT NULL DEFAULT 0,
    UNIQUE (user_id, type, category)
);

CREATE TABLE expenses (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date        text NOT NULL,
    user_id     integer NOT NULL,
    euro        double precision NOT NULL,
    description text,
    category    text,
    type        text
);

CREATE TABLE incomes (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date        text NOT NULL,
    user_id     integer NOT NULL,
    euro        double precision NOT NULL,
    description text
);

CREATE TABLE budgets (
    user_id integer NOT NULL DEFAULT 1,
    year    integer NOT NULL,
    kind    text NOT NULL,
    value   double precision NOT NULL DEFAULT 0,
    period  text NOT NULL DEFAULT 'annuale',
    PRIMARY KEY (user_id, year, kind)
);

CREATE TABLE planned_expenses (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer NOT NULL DEFAULT 1,
    month       text NOT NULL,
    euro        double precision NOT NULL,
    description text NOT NULL DEFAULT '',
    category    text NOT NULL DEFAULT '',
    due_date    text NOT NULL DEFAULT ''
);

CREATE TABLE recurring_expenses (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer NOT NULL DEFAULT 1,
    day_of_month integer NOT NULL,
    euro         double precision NOT NULL,
    type         text NOT NULL,
    category     text NOT NULL,
    description  text DEFAULT '',
    auto_insert  integer NOT NULL DEFAULT 0,
    active       integer NOT NULL DEFAULT 1,
    end_date     text NOT NULL DEFAULT ''
);

CREATE TABLE wealth_slots (
    user_id integer NOT NULL,
    slot    text NOT NULL,
    label   text NOT NULL,
    visible integer NOT NULL DEFAULT 1,
    PRIMARY KEY (user_id, slot)
);

CREATE TABLE wealth_group_settings (
    user_id integer NOT NULL,
    grp     text NOT NULL,
    counts  integer NOT NULL DEFAULT 1,
    PRIMARY KEY (user_id, grp)
);

CREATE TABLE wealth_values (
    user_id integer NOT NULL,
    anno    integer NOT NULL,
    mese    integer NOT NULL,
    slot    text NOT NULL,
    value   double precision NOT NULL,
    PRIMARY KEY (user_id, anno, mese, slot)
);

-- Vecchio patrimonio a colonne fisse (sostituito da wealth_values con la migrazione 005): resta per non
-- perdere dati copiati da database SQLite vecchi.
CREATE TABLE patrimonio (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  integer NOT NULL DEFAULT 1,
    anno     integer NOT NULL,
    mese     integer NOT NULL,
    bcc double precision DEFAULT 0, bbva double precision DEFAULT 0, directa double precision DEFAULT 0,
    deposito double precision DEFAULT 0, obblig double precision DEFAULT 0, etf_etc double precision DEFAULT 0,
    debito double precision DEFAULT 0, credito double precision DEFAULT 0, cauzioni double precision DEFAULT 0,
    tfr double precision DEFAULT 0, fon_te double precision DEFAULT 0,
    UNIQUE (user_id, anno, mese)
);

CREATE TABLE settings (key text PRIMARY KEY, value text NOT NULL);
CREATE TABLE login_attempts (ip text NOT NULL, ts double precision NOT NULL);

CREATE INDEX idx_category_user       ON category (user_id);
CREATE INDEX idx_expenses_category   ON expenses (category COLLATE nocase);
CREATE INDEX idx_expenses_user_date  ON expenses (user_id, date);
CREATE INDEX idx_incomes_user_date   ON incomes (user_id, date);
CREATE INDEX idx_planned_month       ON planned_expenses (month);
CREATE INDEX idx_login_attempts_ip   ON login_attempts (ip, ts);
